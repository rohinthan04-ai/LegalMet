import { useEffect, useState } from "react";
import { Link, useParams } from "react-router-dom";
import { ArrowLeft, Download, FileText, Loader2, RefreshCw } from "lucide-react";
import { downloadBlob, fetchReportPdf, reportFilename } from "../api/reports";
import { listInspections } from "../api/inspections";
import { getErrorMessage } from "../utils/errors";
import { formatDateTime } from "../utils/dates";
import Alert from "../components/common/Alert";
import StatusBadge from "../components/common/StatusBadge";
import WorkflowStepper from "../components/inspection/WorkflowStepper";

export default function Report() {
  const { insId } = useParams();
  const [inspection, setInspection] = useState(null);
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState("");
  const [downloaded, setDownloaded] = useState(false);

  // Basic inspection info for the summary card (from GET /inspections)
  useEffect(() => {
    listInspections()
      .then((list) => setInspection(list.find((item) => String(item.ins_id) === insId) || null))
      .catch(() => {
        /* the summary is optional */
      });
  }, [insId]);

  // GET /inspections/{id}/report builds a fresh PDF from the latest saved details and evaluation,
  // stores it in the database and returns it.
  async function handleGenerate() {
    setGenerating(true);
    setError("");
    setDownloaded(false);
    try {
      const blob = await fetchReportPdf(insId);
      downloadBlob(blob, reportFilename(insId));
      setDownloaded(true);
    } catch (err) {
      setError(getErrorMessage(err));
    } finally {
      setGenerating(false);
    }
  }

  return (
    <div className="mx-auto max-w-2xl">
      <WorkflowStepper current={4} />

      <div className="card p-6">
        <div className="flex items-center gap-3">
          <div className="flex h-11 w-11 items-center justify-center rounded-lg bg-brand-50 text-brand-600">
            <FileText className="h-6 w-6" />
          </div>
          <div>
            <h2 className="text-lg font-semibold text-navy-800">Inspection report</h2>
            <p className="text-sm text-navy-500">{reportFilename(insId)}</p>
          </div>
        </div>

        {inspection && (
          <dl className="mt-5 grid gap-3 rounded-lg bg-navy-50 p-4 text-sm sm:grid-cols-3">
            <div>
              <dt className="text-xs font-semibold uppercase tracking-wide text-navy-500">Category</dt>
              <dd className="capitalize text-navy-800">{inspection.category}</dd>
            </div>
            <div>
              <dt className="text-xs font-semibold uppercase tracking-wide text-navy-500">Date</dt>
              <dd className="text-navy-800">{formatDateTime(inspection.date)}</dd>
            </div>
            <div>
              <dt className="text-xs font-semibold uppercase tracking-wide text-navy-500">Status</dt>
              <dd>
                <StatusBadge status={inspection.status} />
              </dd>
            </div>
          </dl>
        )}

        <p className="mt-5 text-sm text-navy-700">
          The PDF is generated by the server from the details you confirmed and the latest AI evaluation. It contains a space for the inspector's
          signature, and the AI result remains preliminary until you verify the package.
        </p>

        {error && (
          <Alert variant="error" className="mt-4" title="Report could not be generated">
            {error}
            {error.toLowerCase().includes("not found") && " Run the rule evaluation first."}
          </Alert>
        )}
        {downloaded && <Alert variant="success" className="mt-4">Report generated. Your download should start automatically.</Alert>}

        <div className="mt-6 flex flex-wrap justify-between gap-2">
          <Link to="/inspections" className="btn-secondary">
            <ArrowLeft className="h-4 w-4" /> Inspection history
          </Link>
          <button onClick={handleGenerate} disabled={generating} className="btn-primary">
            {generating ? (
              <>
                <Loader2 className="h-4 w-4 animate-spin" /> Generating PDF...
              </>
            ) : downloaded ? (
              <>
                <RefreshCw className="h-4 w-4" /> Generate and download again
              </>
            ) : (
              <>
                <Download className="h-4 w-4" /> Generate and download PDF
              </>
            )}
          </button>
        </div>
      </div>
    </div>
  );
}
